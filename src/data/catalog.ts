function clothingVariants(prefix: string, priceCents: number, colors: string[]): Product["variants"] {
  const sizes = ["S", "M", "L", "XL"];
  return colors.flatMap((color) =>
    sizes.map((size) => ({
      id: `${prefix}-${color.toLowerCase().replace(/\s+/g, "-")}-${size.toLowerCase()}`,
      label: `${color} / ${size}`,
      options: { Color: color, Size: size },
      priceCents,
      sku: `${prefix}-${color.slice(0, 3)}-${size}`.toUpperCase(),
      inventory: 8 + ((color.length + size.length) % 7),
    })),
  );
}

